logger = logging.getLogger(__name__)


def create_results_tab() -> Dict[str, Any]:
    """Constructs Tab 9: Results & Comparison components and event bindings."""
    components = {}

    with gr.Column():
        gr.Markdown("### Simulation Results, Bottleneck Diagnosis & Scenario Comparison")
        gr.Markdown(
            "Examine microscopic simulation outputs generated by upstream engines. "
            "P15-RES-007: Visualizations and tables consume simulation results directly without recalculation."
        )

        with gr.Row():
            components["btn_refresh_results"] = gr.Button("🔄 Refresh Results from Last Run", variant="primary")
            components["export_xlsx_btn"] = gr.Button("📊 Export Results to Excel (.xlsx)", variant="secondary")
            components["export_json_btn"] = gr.Button("📑 Export Results to JSON (.json)", variant="secondary")
            components["export_speed_csv_btn"] = gr.Button("📈 Export Speed Profile CSV (.csv)", variant="secondary")

        components["export_file_download"] = gr.HTML(label="Export File Download Ready", visible=False)

        # Direction Banner
        components["res_direction_banner"] = gr.HTML(
            DirectionSelector.render_banner(session_state.selected_running_direction)
        )

        # Headline KPI Cards
        with gr.Row():
            components["res_kpi_headway"] = gr.HTML("""
                <div class="kpi-card">
                    <div class="kpi-title">Technical Min Headway</div>
                    <div style="font-size: 22px; font-weight: 700; color: #1B365D;">Not Available</div>
                    <div style="font-size: 11px; color: #94a3b8;">Not available — simulation engine not implemented</div>
                </div>
            """)
            components["res_kpi_theo_cap"] = gr.HTML("""
                <div class="kpi-card">
                    <div class="kpi-title">Theoretical Line Capacity</div>
                    <div style="font-size: 22px; font-weight: 700; color: #1B365D;">Not Available</div>
                    <div style="font-size: 11px; color: #94a3b8;">C = 3600 / H</div>
                </div>
            """)
            components["res_kpi_plan_cap"] = gr.HTML("""
                <div class="kpi-card">
                    <div class="kpi-title">Planning Operational Capacity</div>
                    <div style="font-size: 22px; font-weight: 700; color: #1B365D;">Not Available</div>
                    <div style="font-size: 11px; color: #94a3b8;">With planning margin</div>
                </div>
            """)
            components["res_kpi_perf_factor"] = gr.HTML("""
                <div class="kpi-card">
                    <div class="kpi-title">Performance Factor</div>
                    <div style="font-size: 22px; font-weight: 700; color: #1B365D;">100%</div>
                    <div style="font-size: 11px; color: #94a3b8;">Traction & Service Braking</div>
                </div>
            """)
            components["res_kpi_bottleneck"] = gr.HTML("""
                <div class="kpi-card">
                    <div class="kpi-title">Controlling Bottleneck</div>
                    <div style="font-size: 20px; font-weight: 700; color: #DC2626;">Not Available</div>
                    <div style="font-size: 11px; color: #94a3b8;">Critical conflict resource</div>
                </div>
            """)

        gr.Markdown("---")

        # Result Visualizations Sub-Tabs
        with gr.Tabs():
            # Sub-Tab 1: Speed Profile & Dynamics
            with gr.TabItem("Speed & Alignment"):
                components["plot_speed_dynamics"] = gr.Plot(label="Microscopic Speed Profile & Civil Envelopes")

            # Sub-Tab 2: Blocking Stairway & Conflicts
            with gr.TabItem("Blocking Stairway & Conflicts"):
                with gr.Row():
                    with gr.Column(scale=1):
                        components["plot_blocking_stairway"] = gr.Plot(label="Blocking-Time Stairway Diagram")
                    with gr.Column(scale=1):
                        components["plot_seven_components"] = gr.Plot(label="Seven-Component Duration Breakdown")
                gr.Markdown("#### Pairwise Route Conflict Ranking")
                components["tbl_conflicts"] = gr.Dataframe(
                    headers=["Rank", "Resource ID", "Required Headway (s)", "Slack (s)", "Classification"],
                    value=[],
                    interactive=False,
                )

            # Sub-Tab 3: Station & Mixed-Traffic
            with gr.TabItem("Stations & Mixed-Traffic"):
                with gr.Row():
                    with gr.Column(scale=1):
                        components["plot_platform_timeline"] = gr.Plot(label="Station Platform Reservation Timeline")
                    with gr.Column(scale=1):
                        components["plot_mixed_traffic_heatmap"] = gr.Plot(label="Directional Mixed-Traffic Heatmap")
                gr.Markdown("#### Mixed-Traffic Directional Headway Matrix")
                components["tbl_mixed_traffic"] = gr.Dataframe(
                    headers=["Leader Service", "Follower Service", "Required Headway (s)", "Controlling Resource"],
                    value=[],
                    interactive=False,
                )

            # Sub-Tab 4: Operations & TVS
            with gr.TabItem("Operations & TVS"):
                with gr.Row():
                    with gr.Column(scale=1):
                        components["plot_time_distance"] = gr.Plot(label="Multi-Train Time-Distance Diagram")
                    with gr.Column(scale=1):
                        components["plot_tvs_timeline"] = gr.Plot(label="TVS Section Single-Train Occupancy Timeline")

            # Sub-Tab 5: Sensitivity & Stochastic
            with gr.TabItem("Sensitivity & Reliability"):
                with gr.Row():
                    with gr.Column(scale=1):
                        components["plot_block_sensitivity"] = gr.Plot(label="Constrained Block Length Sensitivity")
                    with gr.Column(scale=1):
                        components["plot_stochastic_histogram"] = gr.Plot(label="Monte Carlo Headway Distribution & Quantiles")

            # Sub-Tab 6: Scenario Comparison
            with gr.TabItem("Scenario Comparison"):
                with gr.Row():
                    with gr.Column(scale=1):
                        components["plot_scenario_kpis"] = gr.Plot(label="Scenario KPI Comparison")
                    with gr.Column(scale=1):
                        components["plot_bottleneck_migration"] = gr.Plot(label="Bottleneck Migration Diagram")
                components["tbl_scenario_comparison"] = gr.Dataframe(
                    headers=["Scenario ID", "Metric", "Baseline Value", "Scenario Value", "Absolute Delta", "% Change"],
                    value=[],
                    interactive=False,
                )

    def refresh_results_view() -> Tuple[Any, ...]:
        expected_outputs = 20
        pkg = session_state.latest_result_package
        doc = session_state.latest_report_doc

        if not doc and pkg:
            try:
                from headway.reporting.report_assembly import ReportAssembler
                doc = ReportAssembler.assemble_report(package=pkg)
                session_state.latest_report_doc = doc
            except Exception as exc:
                logger.exception("Failed to assemble report document: %s", exc)
                doc = None

        empty_fig = go.Figure()
        empty_fig.add_annotation(text="No Simulation Results Available — Run in Tab 8", showarrow=False)

        if not pkg or not doc:
            banner = DirectionSelector.render_banner(session_state.selected_running_direction)
            msg = "No simulation results available. Run a simulation in Tab 8 first."
            empty_fig = go.Figure()
            empty_fig.add_annotation(text=msg, showarrow=False)

            k_hw = f"""<div class="kpi-card"><div class="kpi-title">Technical Min Headway</div><div style="font-size: 20px; font-weight: 700; color: #1B365D;">Not Available</div><div style="font-size: 11px; color: #94a3b8;">{msg}</div></div>"""
            k_theo = f"""<div class="kpi-card"><div class="kpi-title">Theoretical Line Capacity</div><div style="font-size: 20px; font-weight: 700; color: #1B365D;">Not Available</div><div style="font-size: 11px; color: #94a3b8;">{msg}</div></div>"""
            k_plan = f"""<div class="kpi-card"><div class="kpi-title">Planning Operational Capacity</div><div style="font-size: 20px; font-weight: 700; color: #1B365D;">Not Available</div><div style="font-size: 11px; color: #94a3b8;">{msg}</div></div>"""
            k_perf = f"""<div class="kpi-card"><div class="kpi-title">Performance Factor</div><div style="font-size: 20px; font-weight: 700; color: #1B365D;">Not Available</div><div style="font-size: 11px; color: #94a3b8;">{msg}</div></div>"""
            k_bot = f"""<div class="kpi-card"><div class="kpi-title">Controlling Bottleneck</div><div style="font-size: 20px; font-weight: 700; color: #DC2626;">Not Available</div><div style="font-size: 11px; color: #94a3b8;">{msg}</div></div>"""
            result = (
                banner, k_hw, k_theo, k_plan, k_perf, k_bot,
                empty_fig, empty_fig, empty_fig, [],
                empty_fig, empty_fig, [],
                empty_fig, empty_fig,
                empty_fig, empty_fig,
                empty_fig, empty_fig, [],
            )
            assert len(result) == expected_outputs, (
                f"refresh_results_view returned {len(result)} values, "
                f"but {expected_outputs} outputs are registered."
            )
            return result

        kpis = doc.executive_kpis
        direction = pkg.running_direction
        banner = DirectionSelector.render_banner(direction)

        k_hw = f"""<div class="kpi-card"><div class="kpi-title">Technical Min Headway</div><div style="font-size: 22px; font-weight: 700; color: #1B365D;">{kpis.technical_headway_s:.1f} s</div><div style="font-size: 11px; color: #94a3b8;">Direction: {direction.value}</div></div>"""
        k_theo = f"""<div class="kpi-card"><div class="kpi-title">Theoretical Line Capacity</div><div style="font-size: 22px; font-weight: 700; color: #1B365D;">{kpis.theoretical_capacity_tph:.1f} tph</div><div style="font-size: 11px; color: #94a3b8;">C = 3600 / H</div></div>"""
        k_plan = f"""<div class="kpi-card"><div class="kpi-title">Planning Operational Capacity</div><div style="font-size: 22px; font-weight: 700; color: #1B365D;">{kpis.planning_capacity_tph:.1f} tph</div><div style="font-size: 11px; color: #94a3b8;">Margin: {kpis.planning_margin_s:.0f} s</div></div>"""
        k_perf = f"""<div class="kpi-card"><div class="kpi-title">Performance Factor</div><div style="font-size: 22px; font-weight: 700; color: #1B365D;">{kpis.performance_factor_str}</div><div style="font-size: 11px; color: #94a3b8;">Source: {kpis.performance_factor_source}</div></div>"""
        k_bot = f"""<div class="kpi-card"><div class="kpi-title">Controlling Bottleneck</div><div style="font-size: 20px; font-weight: 700; color: #DC2626;">{kpis.controlling_bottleneck_id}</div><div style="font-size: 11px; color: #94a3b8;">{kpis.controlling_bottleneck_type}</div></div>"""

        # Figures from doc or visualizers
        primary_traj = next(iter(pkg.trajectories.values()), None)
        fig_speed = (
            create_speed_distance_figure(
                primary_traj,
                permissible_speed_envelope=pkg.metadata.get("permissible_speed_envelope"),
                track_links=pkg.metadata.get("track_links"),
                running_direction=direction,
            )
            if primary_traj
            else empty_fig
        )

        primary_hw = next(iter(pkg.headway_results.values()), None)
        fig_stair = create_blocking_stairway_figure(primary_hw) if primary_hw else empty_fig
        fig_seven = create_seven_component_figure(pkg.blocking_intervals, running_direction=direction) if pkg.blocking_intervals else empty_fig

        # Conflicts table
        conf_rows: List[List[Any]] = []
        if primary_hw and primary_hw.conflict_ranking:
            for rank, c in enumerate(primary_hw.conflict_ranking, start=1):
                conf_rows.append([
                    str(rank),
                    c.leader_resource_id,
                    f"{c.required_headway_s:.1f}",
                    f"{c.slack_s:.1f}",
                    "CONTROLLING BOTTLENECK" if c.slack_s == 0.0 else "NON_CRITICAL",
                ])

        # Station & mixed traffic
        plat_recs = pkg.metadata.get("platform_records", [])
        fig_plat = create_platform_occupation_figure(plat_recs, running_direction=direction) if plat_recs else empty_fig

        mt_matrix = pkg.mixed_traffic_matrix
        fig_mt = create_mixed_traffic_heatmap(mt_matrix) if mt_matrix else empty_fig
        mt_rows: List[List[Any]] = []
        if mt_matrix:
            for (s1, s2), val in mt_matrix.headway_values_s.items():
                mt_rows.append([s1, s2, f"{val:.1f}", mt_matrix.controlling_bottlenecks.get((s1, s2), "-")])

        # Operations and TVS
        fig_td = create_time_distance_figure(list(pkg.trajectories.values()), running_direction=direction) if pkg.trajectories else empty_fig
        tvs_events = pkg.metadata.get("tvs_events", [])
        fig_tvs = create_tvs_occupation_figure(tvs_events, running_direction=direction) if tvs_events else empty_fig

        # Sensitivity and stochastic
        study = pkg.sensitivity_result
        fig_sens = create_block_sensitivity_figure(study, running_direction=direction) if study else empty_fig

        mc = pkg.monte_carlo_result
        samples = pkg.metadata.get("stochastic_headway_samples", [])
        hw_stat = mc.summaries.get("headway_s") if (mc and mc.summaries) else None
        fig_stoch = create_stochastic_histogram_figure(samples, summary=hw_stat, running_direction=direction)

        # Scenario comparison
        report_cmp = pkg.scenario_comparison_report
        fig_cmp = create_scenario_kpi_comparison_figure(report_cmp, running_direction=direction) if report_cmp else empty_fig
        fig_mig = create_bottleneck_migration_figure(report_cmp, running_direction=direction) if report_cmp else empty_fig
        cmp_rows: List[List[Any]] = []
        if report_cmp:
            for scn_id, diffs in report_cmp.metric_differences.items():
                for d in diffs:
                    cmp_rows.append([
                        scn_id,
                        d.metric_name,
                        f"{d.baseline_value:.1f}",
                        f"{d.scenario_value:.1f}",
                        f"{d.absolute_change:+.1f}",
                        f"{d.percentage_change:+.1f}%",
                    ])

        result = (
            banner, k_hw, k_theo, k_plan, k_perf, k_bot,
            fig_speed, fig_stair, fig_seven, conf_rows,
            fig_plat, fig_mt, mt_rows,
            fig_td, fig_tvs,
            fig_sens, fig_stoch,
            fig_cmp, fig_mig, cmp_rows,
        )
        assert len(result) == expected_outputs, (
            f"refresh_results_view returned {len(result)} values, "
            f"but {expected_outputs} outputs are registered."
        )
        return result

    components["btn_refresh_results"].click(
        fn=refresh_results_view,
        inputs=[],
        outputs=[
            components["res_direction_banner"],
            components["res_kpi_headway"],
            components["res_kpi_theo_cap"],
            components["res_kpi_plan_cap"],
            components["res_kpi_perf_factor"],
            components["res_kpi_bottleneck"],
            components["plot_speed_dynamics"],
            components["plot_blocking_stairway"],
            components["plot_seven_components"],
            components["tbl_conflicts"],
            components["plot_platform_timeline"],
            components["plot_mixed_traffic_heatmap"],
            components["tbl_mixed_traffic"],
            components["plot_time_distance"],
            components["plot_tvs_timeline"],
            components["plot_block_sensitivity"],
            components["plot_stochastic_histogram"],
            components["plot_scenario_kpis"],
            components["plot_bottleneck_migration"],
            components["tbl_scenario_comparison"],
        ],
    )

    def export_excel_results() -> Any:
        doc = session_state.latest_report_doc
        if not doc and session_state.latest_result_package:
            doc = ReportAssembler.assemble_report(package=session_state.latest_result_package)
            session_state.latest_report_doc = doc
        if not doc:
            return gr.update(value="<div style='color: #DC2626;'>No results available to export.</div>", visible=True)
        out_dir = Path(session_state.reports_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
        out_path = out_dir / f"Simulation_Results_{doc.metadata.report_id}.xlsx"
        ExcelReportExporter.export(doc, output_path=out_path)
        download_html = FileManager.create_base64_download_link(
            out_path, label=f"Download Excel Results ({out_path.name})"
        )
        return gr.update(value=download_html, visible=True)

    components["export_xlsx_btn"].click(
        fn=export_excel_results,
        inputs=[],
        outputs=[components["export_file_download"]],
    )

    def export_json_results() -> Any:
        doc = session_state.latest_report_doc
        if not doc and session_state.latest_result_package:
            doc = ReportAssembler.assemble_report(package=session_state.latest_result_package)
            session_state.latest_report_doc = doc
        if not doc:
            return gr.update(value="<div style='color: #DC2626;'>No results available to export.</div>", visible=True)
        out_dir = Path(session_state.reports_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
        out_path = out_dir / f"Simulation_Results_{doc.metadata.report_id}.json"
        JsonReportExporter.export(doc, output_path=out_path)
        download_html = FileManager.create_base64_download_link(
            out_path, label=f"Download JSON Results ({out_path.name})"
        )
        return gr.update(value=download_html, visible=True)

    components["export_json_btn"].click(
        fn=export_json_results,
        inputs=[],
        outputs=[components["export_file_download"]],
    )

    def export_speed_csv_results() -> Any:
        pkg = session_state.latest_result_package
        if not pkg or not pkg.trajectories:
            return gr.update(value="<div style='color: #DC2626;'>No trajectory results available to export.</div>", visible=True)
        primary_traj = next(iter(pkg.trajectories.values()))
        env = pkg.metadata.get("permissible_speed_envelope") if pkg.metadata else None
        track_links = pkg.metadata.get("track_links") if pkg.metadata else None
        csv_str = generate_speed_profile_csv(
            primary_traj,
            permissible_speed_envelope=env,
            track_links=track_links,
            running_direction=session_state.selected_running_direction,
        )
        out_dir = Path(session_state.reports_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
        out_path = out_dir / f"Speed_Profile_{pkg.run_id}_{primary_traj.train_id}.csv"
        out_path.write_text(csv_str, encoding="utf-8")
        download_html = FileManager.create_base64_download_link(
            out_path, label=f"Download Speed Profile CSV ({out_path.name})"
        )
        return gr.update(value=download_html, visible=True)

    components["export_speed_csv_btn"].click(
        fn=export_speed_csv_results,
        inputs=[],
        outputs=[components["export_file_download"]],
    )

    return components
